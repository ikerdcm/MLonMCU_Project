#!/usr/bin/env python3
"""
Build an embedded test subset for on-device (device-in-the-loop) accuracy.

Picks PER_CLASS stratified Speech Commands test samples, computes their MFCC
(host pipeline, same as eval_quantized_model.py), quantizes to int8 with the
v2 model's input quant (0.5847 / 83), and writes them as a C header that the
kws_eval firmware runs on the Edge TPU and tallies. Also reports the *host*
accuracy on the same int8 subset (run on ds_cnn_l_static_v2.tflite) so device
vs host on identical inputs isolates accelerator faithfulness.

Usage:  cd platforms/coral && python3 scripts/make_eval_set.py
"""
import os, sys, struct
os.environ['TF_CPP_MIN_LOG_LEVEL'] = '2'
import numpy as np
import tensorflow as tf

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
TRAIN_DIR  = os.path.normpath(os.path.join(SCRIPT_DIR, "../../../training"))
COMMON     = os.path.normpath(os.path.join(SCRIPT_DIR, "../apps/common"))
MODEL      = os.path.normpath(os.path.join(SCRIPT_DIR, "../../../models/ds_cnn_l_static_v2.tflite"))
OUT        = os.path.join(COMMON, "ds_cnn_eval_set.h")
sys.path.insert(0, TRAIN_DIR)
import kws_util
import get_dataset as kws_data

PER_CLASS = 12   # 12*12=144 samples; keeps the embedded int8 array within internal flash (m_text)
NCLASS    = 12
SCALE, ZP = 0.5847026705741882, 83

Flags, _ = kws_util.parse_command()
_, ds_test, _ = kws_data.get_training_data(Flags)
ds = ds_test.unbatch().as_numpy_iterator()

buckets = {i: [] for i in range(NCLASS)}
for mfcc, label in ds:
    l = int(label)
    if len(buckets[l]) < PER_CLASS:
        q = np.clip(np.round(mfcc.astype(np.float32) / SCALE + ZP), -128, 127).astype(np.int8)
        buckets[l].append(q.reshape(-1))
    if all(len(v) >= PER_CLASS for v in buckets.values()):
        break

feats, labels = [], []
for l in range(NCLASS):
    for q in buckets[l]:
        feats.append(q); labels.append(l)
feats = np.array(feats, dtype=np.int8); labels = np.array(labels, dtype=np.uint8)
N = len(labels)
print(f"subset: {N} samples, per-class counts = {[len(buckets[i]) for i in range(NCLASS)]}")

# Host baseline on the SAME int8 inputs (v2 static; int8 fed directly)
it = tf.lite.Interpreter(model_path=MODEL); it.allocate_tensors()
di, oi = it.get_input_details()[0], it.get_output_details()[0]
correct = 0
for i in range(N):
    it.set_tensor(di['index'], feats[i].reshape(di['shape']).astype(np.int8)); it.invoke()
    if int(np.argmax(it.get_tensor(oi['index']))) == labels[i]:
        correct += 1
print(f"HOST v2 acc on subset: {correct}/{N} = {100*correct/N:.2f}%")

flat = feats.reshape(-1)
with open(OUT, "w") as f:
    f.write("#ifndef DS_CNN_EVAL_SET_H\n#define DS_CNN_EVAL_SET_H\n")
    f.write(f"// {N} stratified Speech Commands test samples, int8 MFCC "
            f"(scale {SCALE}, zp {ZP}) for ds_cnn_l_static_v2.\n")
    f.write("// Generated by platforms/coral/scripts/make_eval_set.py -- do not edit.\n")
    f.write(f"#define EVAL_N {N}\n#define EVAL_INPUT_SIZE 490\n\n")
    f.write(f"static const signed char eval_features[{N} * 490] = {{\n")
    for i in range(0, len(flat), 24):
        f.write("  " + ",".join(str(int(x)) for x in flat[i:i+24]) + ",\n")
    f.write("};\n\n")
    f.write(f"static const unsigned char eval_labels[{N}] = {{\n  "
            + ",".join(str(int(x)) for x in labels) + "\n};\n\n")
    f.write("#endif  // DS_CNN_EVAL_SET_H\n")
print(f"wrote {OUT}")

# Binary form for LittleFS-loading apps (e.g. kws_eval_cpu, which can't embed it
# in internal flash): uint32 N (LE) + N*490 int8 features + N uint8 labels.
OUT_BIN = os.path.join(COMMON, "ds_cnn_eval_set.bin")
with open(OUT_BIN, "wb") as bf:
    bf.write(struct.pack("<I", N))
    bf.write(feats.astype(np.int8).tobytes())
    bf.write(labels.astype(np.uint8).tobytes())
print(f"wrote {OUT_BIN} ({4 + N*490 + N} bytes)")
